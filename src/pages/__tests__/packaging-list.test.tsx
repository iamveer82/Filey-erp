it("duplicates item details with a fresh identity and saves the chosen item order", async () => {
  vi.mocked(savePackagingList).mockImplementation(async (form) => ({ id: "packing-3", revision: 1, created_at: "2026-10-01", updated_at: "2026-10-01", form }));
  render(<MemoryRouter><UIProvider><PackagingList /></UIProvider></MemoryRouter>);
  const create = await screen.findByRole("button", { name: "New packaging list" });
  await waitFor(() => expect(create).toBeEnabled());
  await act(async () => { fireEvent.click(create); });
  fireEvent.change(screen.getByLabelText(/^Recipient name/), { target: { value: "Shipment recipient" } });
  fireEvent.mouseDown(screen.getByRole("tab", { name: "Items" }), { button: 0, ctrlKey: false });
  fireEvent.change(screen.getByLabelText(/^Description/), { target: { value: "Original contents" } });
  fireEvent.change(screen.getByLabelText("Quantity"), { target: { value: "3" } });
  fireEvent.change(screen.getByLabelText("Packages"), { target: { value: "2" } });
  fireEvent.change(screen.getByLabelText("Net / unit (kg)"), { target: { value: "3.5" } });
  fireEvent.change(screen.getByLabelText("Gross / unit (kg)"), { target: { value: "4" } });
  expect(screen.getByRole("button", { name: "Move item 1 up" })).toBeDisabled();
  expect(screen.getByRole("button", { name: "Move item 1 down" })).toBeDisabled();
  fireEvent.click(screen.getByRole("button", { name: "Duplicate item 1" }));
  const copied = within(screen.getByRole("region", { name: "Item 2" }));
  expect(copied.getByLabelText("Quantity")).toHaveValue(3);
  expect(copied.getByLabelText("Packages")).toHaveValue(2);
  expect(copied.getByLabelText("Net / unit (kg)")).toHaveValue(3.5);
  expect(copied.getByLabelText("Gross / unit (kg)")).toHaveValue(4);
  fireEvent.change(copied.getByLabelText(/^Description/), { target: { value: "Copied contents" } });
  fireEvent.click(screen.getByRole("button", { name: "Move item 2 up" }));
  expect(screen.getAllByLabelText(/^Description/).map((input) => (input as HTMLTextAreaElement).value)).toEqual(["Copied contents", "Original contents"]);
  fireEvent.click(screen.getByRole("button", { name: "Move item 1 down" }));
  expect(screen.getAllByLabelText(/^Description/).map((input) => (input as HTMLTextAreaElement).value)).toEqual(["Original contents", "Copied contents"]);
  fireEvent.click(screen.getByRole("button", { name: "Move item 2 up" }));
  fireEvent.click(screen.getByRole("button", { name: "Save" }));
  await waitFor(() => expect(savePackagingList).toHaveBeenCalledTimes(1));
  const saved = vi.mocked(savePackagingList).mock.calls[0][0].items;
  expect(saved.map((item) => item.description)).toEqual(["Copied contents", "Original contents"]);
  expect(new Set(saved.map((item) => item.id)).size).toBe(2);
  expect(saved.every((item) => item.qty === 3 && item.package_count === 2 && item.net_weight === 3.5 && item.gross_weight === 4)).toBe(true);
});

it("waits for company and numbering defaults while keeping pending optional lookups independent", async () => {
  let resolveCompany!: (company: CompanyProfile) => void;
  let resolveFormats!: (formats: DocFormats) => void;
  let resolveInvoices!: (invoices: InvoiceDocSummary[]) => void;
  vi.mocked(billing.getCompany).mockReturnValueOnce(new Promise((resolve) => { resolveCompany = resolve; }));
  vi.mocked(loadDocFormats).mockReturnValueOnce(new Promise((resolve) => { resolveFormats = resolve; }));
  vi.mocked(billing.listDocs).mockReturnValueOnce(new Promise((resolve) => { resolveInvoices = resolve; }));
  render(<MemoryRouter><UIProvider><PackagingList /></UIProvider></MemoryRouter>);
  const create = await screen.findByRole("button", { name: "New packaging list" });
  expect(create).toBeDisabled();
  resolveCompany({ name: "Saved company", default_accent: "#222222", default_template: "minimal" });
  await waitFor(() => expect(billing.getCompany).toHaveBeenCalled());
  expect(create).toBeDisabled();
  resolveFormats({ packaging_list: "SHIP-{001}" });
  await waitFor(() => expect(create).toBeEnabled());
  await act(async () => { fireEvent.click(create); });
  expect(screen.getByLabelText("Company name")).toHaveValue("Saved company");
  expect(pickDocNumber).toHaveBeenCalledWith("packaging_list", [], { packaging_list: "SHIP-{001}" });
  expect(screen.getByLabelText("Optional invoice reference")).toBeDisabled();
  expect(screen.getByLabelText(/^Recipient name/)).toBeEnabled();
  fireEvent.change(screen.getByLabelText(/^Recipient name/), { target: { value: "Manual recipient" } });
  resolveInvoices([]);
  await waitFor(() => expect(screen.getByLabelText("Optional invoice reference")).toBeEnabled());
  expect(screen.getByLabelText(/^Recipient name/)).toHaveValue("Manual recipient");
});
