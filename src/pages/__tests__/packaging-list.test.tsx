it("distinguishes missing shipment totals from zero and shares the exact saved version", async () => {
  vi.mocked(savePackagingList).mockImplementation(async (form) => ({ id: "packing-totals", revision: 1, created_at: "2026-10-03", updated_at: "2026-10-03T12:00:00Z", form }));
  render(<MemoryRouter><UIProvider><PackagingList /></UIProvider></MemoryRouter>);
  const create = await screen.findByRole("button", { name: "New packaging list" });
  await waitFor(() => expect(create).toBeEnabled());
  await act(async () => { fireEvent.click(create); });
  fireEvent.change(screen.getByLabelText(/^Recipient name/), { target: { value: "Mary" } });
  fireEvent.mouseDown(screen.getByRole("tab", { name: "Items" }), { button: 0, ctrlKey: false });
  fireEvent.change(screen.getByLabelText(/^Description/), { target: { value: "Samples" } });
  const totals = within(screen.getByRole("region", { name: "Shipment totals" }));
  expect(totals.getByText("— packages")).toBeInTheDocument();
  expect(totals.getByText("Net — kg")).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "Share" }));
  await waitFor(() => expect(DocumentMessageDialog).toHaveBeenCalled());
  const calls = vi.mocked(DocumentMessageDialog).mock.calls;
  expect(calls[calls.length - 1][0]).toEqual(expect.objectContaining({ documentVersion: "1:2026-10-03T12:00:00Z", message: expect.not.stringContaining("Packages:") }));
  await waitFor(() => expect(screen.getByLabelText("Packages")).toBeEnabled());
  fireEvent.change(screen.getByLabelText("Packages"), { target: { value: "0" } });
  expect(totals.getByText("0 packages")).toBeInTheDocument();
  fireEvent.click(screen.getByRole("button", { name: "Add item" }));
  expect(totals.getByText(/Totals include entered values/)).toBeInTheDocument();
});

it("keeps a failed standalone draft and updates the saved record by ID and revision", async () => {
  vi.mocked(savePackagingList).mockRejectedValueOnce(new Error("Storage unavailable")).mockImplementation(async (form, id, revision) => ({ id: id || "packing-1", revision: (revision || 0) + 1, created_at: "2026-10-01", updated_at: "2026-10-01", form }));
  render(<MemoryRouter><UIProvider><PackagingList /></UIProvider></MemoryRouter>);
  const create = await screen.findByRole("button", { name: "New packaging list" });
  await waitFor(() => expect(create).toBeEnabled());
  await act(async () => { fireEvent.click(create); });
  fireEvent.change(screen.getByLabelText(/^Recipient name/), { target: { value: "Independent recipient" } });
  fireEvent.mouseDown(screen.getByRole("tab", { name: "Items" }), { button: 0, ctrlKey: false });
  fireEvent.change(screen.getByLabelText(/^Description/), { target: { value: "Carton of samples" } });
  fireEvent.click(screen.getByRole("button", { name: "Save" }));
  await screen.findByText("Storage unavailable");
  expect(screen.getByLabelText(/^Description/)).toHaveValue("Carton of samples");
  fireEvent.click(screen.getByRole("button", { name: "Save" }));
  await waitFor(() => expect(savePackagingList).toHaveBeenCalledTimes(2));
  await waitFor(() => expect(screen.getByRole("button", { name: "Save" })).toBeEnabled());
  fireEvent.change(screen.getByLabelText(/^Description/), { target: { value: "Updated samples" } });
  fireEvent.click(screen.getByRole("button", { name: "Save" }));
  await waitFor(() => expect(savePackagingList).toHaveBeenCalledTimes(3));
  expect(vi.mocked(savePackagingList).mock.calls[2]).toEqual([expect.objectContaining({ recipient_name: "Independent recipient", invoice_id: null, invoice_reference: "", items: [expect.objectContaining({ description: "Updated samples" })] }), "packing-1", 1, "2026-10-01"]);
  await waitFor(() => expect(autoSaveDocument).toHaveBeenLastCalledWith("PL-0001-v2-2026-10-01.pdf", "packing-list", expect.any(Function)));
  expect(billing.saveDoc).not.toHaveBeenCalled();
});

