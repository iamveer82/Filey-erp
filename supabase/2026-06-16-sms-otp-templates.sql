-- Trigger: set updated_at
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

drop trigger if exists set_updated_at on sms_providers;
create trigger set_updated_at before update on sms_providers
  for each row execute procedure set_updated_at();

drop trigger if exists set_updated_at on sms_templates;
create trigger set_updated_at before update on sms_templates
  for each row execute procedure set_updated_at();

drop trigger if exists set_updated_at on custom_entity_fields;
create trigger set_updated_at before update on custom_entity_fields
  for each row execute procedure set_updated_at();

drop trigger if exists set_updated_at on custom_entity_values;
create trigger set_updated_at before update on custom_entity_values
  for each row execute procedure set_updated_at();
