-- Fan out @mentions in a new message to the mentioned org members.
-- Handle = first name (lowercased), matching MentionInput's insertion.
create or replace function public.notify_mentions()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  actor_name text;
  h text;
  rec record;
begin
  select coalesce(name, email, 'Someone') into actor_name
    from public.profiles where id = new.user_id;
  for h in
    select distinct lower(t[1])
    from regexp_matches(new.body, '@([A-Za-z0-9_.\-]+)', 'g') as t
  loop
    for rec in
      select p.id
      from public.profiles p
      join public.org_members om
        on om.user_id = p.id and om.org_id = new.org_id
      where lower(split_part(p.name, ' ', 1)) = h
        and p.id <> new.user_id
    loop
      insert into public.notifications (org_id, user_id, actor, kind, body, link)
      values (new.org_id, rec.id, actor_name, 'mention',
              left(new.body, 140), '/overview');
    end loop;
  end loop;
  return new;
end $$;

