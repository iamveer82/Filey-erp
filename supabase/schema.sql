523|-- Caller's active organization key (text). Defaults to 'default' so any
524|-- pre-existing single-user data keeps working unchanged after migration.
525|create or replace function public.current_org()
526|returns text language sql stable security definer set search_path = public as $$
527|  select coalesce(
528|    (select org_id from public.profiles where id = auth.uid()),
529|    'default'
530|  )
531|$$;
532|
533|-- SECURITY: force org_id to the caller's active org and make it immutable.
534|-- Without this, a client could INSERT a row carrying ANOTHER org's org_id
535|-- (and shared=true) — the per-member RLS check passes on the user_id branch
536|-- regardless of org_id, so the row would surface in the victim org's shared
537|-- feed (cross-tenant injection / fake-invoice phishing). On UPDATE we pin
538|-- org_id to its previous value so a row can never be moved between orgs.
539|create or replace function public.force_org_id()
540|returns trigger language plpgsql security definer set search_path = public as $$
541|begin
542|  -- Admin / service_role / SQL-migration context (no JWT) is trusted and must
543|  -- stay able to backfill org_id. Only pin org_id for real client requests.
544|  if auth.uid() is null then
545|    return new;
546|  end if;
547|  if (TG_OP = 'INSERT') then
548|    new.org_id := public.current_org();
549|  else
550|    new.org_id := old.org_id;
551|  end if;
552|  return new;
553|end $$;
