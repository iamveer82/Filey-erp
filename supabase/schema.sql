555|-- True when the caller is an owner/admin of their active org.
556|-- security definer avoids RLS recursion on org_members.
557|create or replace function public.is_org_admin()
558|returns boolean language sql stable security definer set search_path = public as $$
559|  select exists (
560|    select 1 from public.org_members
561|    where org_id = public.current_org()
562|      and user_id = auth.uid()
563|      and role in ('owner', 'admin')
564|  )
565|$$;
