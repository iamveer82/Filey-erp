1134|-- ---------- audit log: auto-record create/update/delete ----------
1135|-- Populates audit_log for key entities with the acting user + entity ref.
1136|-- security definer so it can write the row regardless of the caller's RLS;
1137|-- failures never block the underlying operation.
1138|create or replace function public.log_audit()
1139|returns trigger language plpgsql security definer set search_path = public as $$
1140|declare
1141|  actor_name text;
1142|  rid text;
1143|begin
1144|  begin
1145|    select coalesce(name, email, 'system') into actor_name
1146|      from public.profiles where id = auth.uid();
1147|    if (TG_OP = 'DELETE') then rid := old.id::text; else rid := new.id::text; end if;
1148|    insert into public.audit_log (actor, action, entity, details, org_id, user_id)
1149|    values (
1150|      coalesce(actor_name, 'system'),
1151|      lower(TG_OP),
1152|      TG_TABLE_NAME,
1153|      TG_TABLE_NAME || ' #' || coalesce(rid, '?'),
1154|      public.current_org(),
1155|      auth.uid()
1156|    );
1157|  exception when others then
1158|    null; -- never let auditing break the real write
1159|  end;
1160|  if (TG_OP = 'DELETE') then return old; else return new; end if;
1161|end $$;
