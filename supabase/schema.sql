-- ---------- local → cloud push support ----------
-- After "Push local data to cloud" inserts rows with their original local ids,
-- each identity sequence must jump past max(id) or the next normal insert
-- collides. Security definer (sequences need owner rights); only ever moves
-- sequences FORWARD to the table''s current max — harmless to call anytime.
create or replace function public.sync_bump_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $fn$
declare
  t text;
  seq text;
  mx bigint;
  tables text[] := array[
    'products','orders','order_items',
    'employees','attendance','payroll',
    'accounts','expenses','transactions',
    'app_users','app_settings','audit_log',
    'crm_leads','crm_customers','crm_opportunities','crm_activities',
    'company_profile','invoice_docs','invoice_doc_items','invoice_payments',
    'quotations','quotation_items','quotation_templates','tool_runs',
    'suppliers','purchase_orders','purchase_order_items','stock_movements',
    'advances','po_payments','payment_receipts','entity_links','follow_ups',
    'invoice_recurrence','notifications',
    'campaigns','email_optouts'
  ];
begin
  foreach t in array tables loop
    begin
      seq := pg_get_serial_sequence('public.' || quote_ident(t), 'id');
      if seq is null then continue; end if;
      execute format('select coalesce(max(id),0) from public.%I', t) into mx;
      if mx > 0 then
        perform setval(seq, mx);
      end if;
    exception when others then
      null; -- table without numeric id / missing table: skip
    end;
  end loop;
end $fn$;

revoke all on function public.sync_bump_sequences() from public;
grant execute on function public.sync_bump_sequences() to authenticated;

