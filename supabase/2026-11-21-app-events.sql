-- ============================================================
-- Live events from connected apps (Composio triggers)
-- ------------------------------------------------------------
-- A customer turns on an event for an app they connected through
-- Composio ("new Gmail message", "new Typeform response"…). Composio
-- delivers each event to the `composio-webhook` edge function, which
-- checks the signature, finds the customer by trigger id and stores the
-- event here. The desktop app reads events through the `integrations`
-- function; always-on automations can run on them.
--
-- Service-role only, like the Instagram tables: the app never touches
-- these directly, so a tampered client can neither read another
-- workspace's events nor forge one.
--
-- Run once (idempotent):
--   supabase db execute --file supabase/2026-11-21-app-events.sql
-- Pairs with: supabase/functions/composio-webhook, .../integrations,
--             src/lib/appEvents.ts, src/pages/AppConnect.tsx
-- ============================================================

-- One row per event a customer turned on. The id is Composio's trigger
-- instance id (ti_...), which every delivered event names.
create table if not exists public.app_triggers (
  id text primary key,
  org_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  entity text not null,                          -- the Composio user_id Filey uses for this org member
  toolkit text not null,
  trigger_slug text not null,
  connected_account_id text not null,
  config jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists app_triggers_owner on public.app_triggers (org_id, user_id);

-- Delivered events. Kept 30 days; the webhook prunes older rows now and then.
create table if not exists public.app_events (
  id bigint generated by default as identity primary key,
  event_key text not null unique,                -- Composio's message id: a redelivery stores nothing twice
  trigger_id text references public.app_triggers(id) on delete set null,
  org_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  toolkit text not null,
  trigger_slug text not null,
  data jsonb not null default '{}'::jsonb,
  received_at timestamptz not null default now()
);
create index if not exists app_events_owner on public.app_events (org_id, user_id, id desc);
create index if not exists app_events_received on public.app_events (received_at);

alter table public.app_triggers enable row level security;
alter table public.app_events enable row level security;

-- No client policies: reads and writes go through the edge functions.
revoke all on public.app_triggers from public, anon, authenticated;
revoke all on public.app_events from public, anon, authenticated;
grant all on public.app_triggers to service_role;
grant all on public.app_events to service_role;
